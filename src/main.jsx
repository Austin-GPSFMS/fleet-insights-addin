/**
 * Entry point — registers the MyGeotab page add-in `fleetInsights`.
 * Re-renders on focus so the top group filter is honoured when it changes.
 */
import { createRoot } from "react-dom/client";
import App from "./App.jsx";
import zenithCss from "./generated/zenith.css"; // generated by build.mjs (fonts stripped)
import customCss from "./styles.css";

/* global geotab */

const STYLE_ID = "fi-addin-styles";

function ensureStyles() {
    if (document.getElementById(STYLE_ID)) return;
    const style = document.createElement("style");
    style.id = STYLE_ID;
    style.textContent = zenithCss + "\n" + customCss;
    document.head.appendChild(style);
}

function readGroupFilter(state) {
    try {
        const g = state && typeof state.getGroupFilter === "function" ? state.getGroupFilter() : null;
        return Array.isArray(g) ? g.map(x => ({ id: x.id })) : [];
    } catch (e) { return []; }
}

if (typeof geotab !== "undefined") {
    geotab.addin = geotab.addin || {};
    geotab.addin.fleetInsights = function () {
        let root = null;
        let container = null;
        let focusNonce = 0;

        function mount(api, state) {
            if (!container) {
                container =
                    document.getElementById("fleetInsights-root") ||
                    document.getElementById("checkmateContent") ||
                    document.body;
            }
            ensureStyles();
            if (!root) {
                const host = document.createElement("div");
                host.className = "fi-page-host";
                container.appendChild(host);
                root = createRoot(host);
            }
            root.render(<App api={api} groupFilter={readGroupFilter(state)} focusNonce={focusNonce} />);
        }

        return {
            initialize(api, state, initializeCallback) {
                mount(api, state);
                initializeCallback();
            },
            focus(api, state) {
                focusNonce++;
                mount(api, state);
            },
            blur() { /* keep state */ }
        };
    };
}
